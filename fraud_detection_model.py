# 3. Anomaly Explainer (Human-Readable Reasoning)
# ---------------------------------------------------------------------------

def explain_fraud_reasons(
    row: pd.Series,
    risk_score: float,
    category_sanction_median: float = 0.0,
    category_unit_cost_median: float = 0.0,
) -> List[str]:
    """
    Generates human-readable explanations for judges and audit officers.
    Translates model findings into actionable fraud red flags.
    """
    reasons = []

    # Priority 1: Physical / Photographic Evidence Checks
    # Evaluated before financial health checks so physical discrepancies are never suppressed.
    gps_dist = float(row.get("gps_distance_km", 0.0)) if pd.notna(row.get("gps_distance_km", 0.0)) else 0.0
    if gps_dist >= 5.0:
        reasons.append(
            f"Geospatial Discrepancy: Evidence photo location is {gps_dist:.1f} km away from registered project site."
        )

    dup_photo = str(row.get("duplicate_photo_flag", "No")).strip().lower()
    if dup_photo in ["yes", "true", "1"]:
        reasons.append(
            "Duplicate Photographic Evidence: Inspection image hash matches an existing project record."
        )

    sanctioned = float(row.get("sanctioned_amount", 0.0))
    expenditure = float(row.get("expenditure_amount", 0.0))
    released = float(row.get("released_amount", sanctioned))
    recommended = float(row.get("recommended_amount", sanctioned))
    physical_pct = float(row.get("physical_progress_pct", 0.0))

    fin_pct = (expenditure / (sanctioned + 1.0)) * 100.0
    gap = fin_pct - physical_pct
    cost_ratio = expenditure / (sanctioned + 1.0)
    release_ratio = expenditure / (released + 1.0)
    sanct_ratio = sanctioned / (recommended + 1.0)
    unit_cost = expenditure / (physical_pct + 1.0)

    # Health Check: If the project is strictly within sanctioned budget, has zero progress lag,
    # has no sanction anomaly, AND has no physical/photo red flags, it is a healthy execution.
    is_healthy = (cost_ratio <= 1.02) and (gap <= 5.0) and (sanct_ratio <= 1.20)
    if is_healthy and risk_score < 60.0 and not reasons:
        return ["Within normal operational and financial parameters."]

    # Rule 1: High financial expenditure with low physical progress (Ghost Project / Fund Siphoning)
    if gap >= 35.0:
        reasons.append(
            f"Severe Fund-Progress Mismatch: {fin_pct:.1f}% funds expended while physical progress is only {physical_pct:.1f}% (Gap: {gap:.1f}%)."
        )
    elif gap >= 20.0:
        reasons.append(
            f"Moderate Progress Lag: Financial burn ({fin_pct:.1f}%) significantly outpaces on-ground completion ({physical_pct:.1f}%)."
        )

    # Rule 2: Cost Overrun
    if cost_ratio >= 1.25:
        reasons.append(
            f"Severe Cost Overrun: Actual expenditure is {cost_ratio:.2f}x of sanctioned budget (INR {expenditure:,.0f} spent vs INR {sanctioned:,.0f} sanctioned)."
        )
    elif cost_ratio > 1.05:
        reasons.append(
            f"Budget Exceeded: Expenditure exceeds sanctioned limit by {((cost_ratio - 1.0) * 100):.1f}%."
        )

    # Rule 3: Fund Overdraw (Expenditure > Released amount)
    if release_ratio >= 1.20:
        reasons.append(
            f"Unauthorized Overdraw: Expenditure is {release_ratio:.2f}x the funds officially released."
        )

    # Rule 4: Excessive Sanction Padding (Sanctioned far exceeds recommendation)
    if sanct_ratio >= 1.50:
        reasons.append(
            f"Sanction Discrepancy: Sanctioned amount is {sanct_ratio:.2f}x of recommended estimate (INR {sanctioned:,.0f} vs INR {recommended:,.0f})."
        )

    # Rule 5: Sector Unit-Cost Inefficiency (Expenditure per % progress is abnormal AND progress is lagging)
    if category_unit_cost_median > 0:
        unit_ratio = unit_cost / category_unit_cost_median
        if unit_ratio >= 2.5 and gap >= 15.0:
            reasons.append(
                f"Sector Unit-Cost Inefficiency: Expenditure per progress unit is {unit_ratio:.1f}x higher than sector median."
            )

    # Rule 6: Sector Budget Outlier (Abnormally high sanctioned budget combined with budget strain)
    if category_sanction_median > 0:
        sanct_scale_ratio = sanctioned / category_sanction_median
        if sanct_scale_ratio >= 2.5 and (cost_ratio > 1.05 or gap > 20.0):
            reasons.append(
                f"Sector Budget Outlier: Sanctioned budget is {sanct_scale_ratio:.1f}x higher than sector median."
            )

    # Rule 7: Project Completion Delay
    delay_days = 0.0
    if "completion_delay_days" in row and pd.notna(row["completion_delay_days"]):
        delay_days = float(row["completion_delay_days"])
    elif "expected_completion_date" in row and "actual_completion_date" in row:
        exp_dt = pd.to_datetime(row["expected_completion_date"], errors="coerce")
        act_dt = pd.to_datetime(row["actual_completion_date"], errors="coerce")
        if pd.notna(exp_dt) and pd.notna(act_dt):
            delay_days = float((act_dt - exp_dt).days)

    if delay_days >= 45.0:
        reasons.append(
            f"Chronic Project Delay: Execution was delayed by {delay_days:.0f} days past the expected completion deadline."
        )

    # Fallback if isolation forest flagged high multidimensional anomaly without a single extreme breach
    if not reasons and risk_score >= 60.0:
        reasons.append(
            "Multivariate Anomaly: Joint distribution of financial burn, project scale, and progress significantly deviates from historic norms."
        )

    return reasons


