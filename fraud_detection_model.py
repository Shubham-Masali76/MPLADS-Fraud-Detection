def normalize_columns(df: pd.DataFrame) -> pd.DataFrame:
    """
    Standardizes dataframe column names using alias matching.
    Ensures team compatibility regardless of minor naming differences in CSVs.
    """
    df = df.copy()
    cleaned_cols = {col: str(col).strip().lower().replace(" ", "_") for col in df.columns}
    df.rename(columns=cleaned_cols, inplace=True)

    rename_map = {}
    for standard_name, aliases in COLUMN_ALIASES.items():
        if standard_name in df.columns:
            continue
        for alias in aliases:
            if alias in df.columns:
                rename_map[alias] = standard_name
                break

    if rename_map:
        df.rename(columns=rename_map, inplace=True)

    return df


def load_dataset(source: Union[str, pd.DataFrame]) -> pd.DataFrame:
    """
    Loads an MPLADS dataset from a CSV path or accepts an existing DataFrame,
    normalizes column headers, and performs essential validation.
    """
    if isinstance(source, pd.DataFrame):
        df = source.copy()
    elif isinstance(source, str):
        if not os.path.exists(source):
            raise FileNotFoundError(f"Dataset file not found at: {source}")
        df = pd.read_csv(source)
    else:
        raise ValueError("Source must be a file path (str) or pandas DataFrame.")

    df = normalize_columns(df)

    # Validate presence of minimum required financial fields
    required_financial_fields = ["sanctioned_amount", "expenditure_amount"]
    missing = [f for f in required_financial_fields if f not in df.columns]
    if missing:
        raise KeyError(
            f"Dataset missing essential columns: {missing}. "
            f"Available columns: {list(df.columns)}"
        )

    return df


def load_and_merge_generated_dataset(
    data_dir: str = "data",
    include_photos: bool = True,
) -> pd.DataFrame:
    """
    Loads and merges the relational CSV tables generated by generate_data.py:
    1. data/projects.csv (Master project records, categories, sanctioned budgets, dates)
    2. data/utilization.csv (Actual utilized funds & physical completion percentage)
    3. data/photo_evidence.csv (Optional: GPS distance deviations & duplicate photo flags)

    Returns a clean, unified DataFrame ready for model training or inference.
    """
    projects_path = os.path.join(data_dir, "projects.csv")
    utilization_path = os.path.join(data_dir, "utilization.csv")
    photo_path = os.path.join(data_dir, "photo_evidence.csv")

    if not os.path.exists(projects_path):
        raise FileNotFoundError(
            f"Projects master table not found at: {projects_path}. "
            f"Please run 'python generate_data.py' first to populate the {data_dir}/ directory."
        )
    if not os.path.exists(utilization_path):
        raise FileNotFoundError(
            f"Utilization table not found at: {utilization_path}. "
            f"Please run 'python generate_data.py' first to populate the {data_dir}/ directory."
        )

    print(f"[*] Ingesting relational tables from '{data_dir}/'...")
    projects_df = pd.read_csv(projects_path)
    utilization_df = pd.read_csv(utilization_path)

    projects_df = normalize_columns(projects_df)
    utilization_df = normalize_columns(utilization_df)

    # Merge projects with utilization on project_id
    merged = pd.merge(
        projects_df,
        utilization_df,
        on="project_id",
        how="inner",
        suffixes=("", "_uc"),
    )

    # Optionally merge photo evidence
    if include_photos and os.path.exists(photo_path):
        photo_df = pd.read_csv(photo_path)
        photo_df = normalize_columns(photo_df)

        photo_cols = ["project_id"]
        for col in ["gps_distance_km", "duplicate_photo_flag", "gps_verification"]:
            if col in photo_df.columns:
                photo_cols.append(col)

        photo_sub = photo_df[photo_cols].drop_duplicates(subset=["project_id"])
        merged = pd.merge(
            merged,
            photo_sub,
            on="project_id",
            how="left",
            suffixes=("", "_photo"),
        )
        print(f"[+] Merged projects ({len(projects_df):,} rows) with utilization and photo evidence.")
    else:
        print(f"[+] Merged projects ({len(projects_df):,} rows) with utilization.")

    merged = normalize_columns(merged)
    return merged


