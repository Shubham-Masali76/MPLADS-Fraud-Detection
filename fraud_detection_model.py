class MPLADSFeatureEngineer:
    """
    Extracts anti-corruption and fraud indicators tailored to government works:
    - Fund-Progress Mismatch (Money spent vs actual physical progress on ground)
    - Cost Overrun Ratio (Expenditure vs Sanctioned Budget)
    - Fund Release Utilization (Expenditure vs Released funds)
    - Sanction Discrepancy (Sanctioned vs Recommended amount)
    - Sector Cost Deviations (Z-score / ratio against category medians)
    """

    def __init__(self):
        self.scaler = RobustScaler()
        self.fitted = False
        self.feature_names: List[str] = []
        self.category_sanction_medians: Dict[str, float] = {}
        self.overall_median_sanctioned: float = 0.0
        self.category_unit_cost_medians: Dict[str, float] = {}
        self.overall_median_unit_cost: float = 0.0

    def fit(self, df: pd.DataFrame) -> "MPLADSFeatureEngineer":
        """Calculates category baselines and fits numerical scalers."""
        df = normalize_columns(df)

        sanctioned = pd.to_numeric(df.get("sanctioned_amount", 0.0), errors="coerce").fillna(0.0)
        expenditure = pd.to_numeric(df.get("expenditure_amount", 0.0), errors="coerce").fillna(0.0)
        physical_pct = pd.to_numeric(df.get("physical_progress_pct", 0.0), errors="coerce").fillna(0.0)
        unit_costs = expenditure / (physical_pct + 1.0)

        # Baseline category metrics (sanctioned budget and unit cost efficiency)
        if "category" in df.columns:
            df_temp = df.copy()
            df_temp["_sanct"] = sanctioned
            df_temp["_unit_cost"] = unit_costs

            self.category_sanction_medians = df_temp.groupby("category")["_sanct"].median().to_dict()
            self.category_unit_cost_medians = df_temp.groupby("category")["_unit_cost"].median().to_dict()

        self.overall_median_sanctioned = float(sanctioned.median()) if len(sanctioned) > 0 else 1000000.0
        self.overall_median_unit_cost = float(unit_costs.median()) if len(unit_costs) > 0 else 10000.0

        features_df = self._derive_indicators(df)
        self.feature_names = list(features_df.columns)
        self.scaler.fit(features_df.values)
        self.fitted = True
        return self

    def transform(self, df: pd.DataFrame) -> np.ndarray:
        """Transforms raw dataframe into scaled numerical feature array."""
        if not self.fitted:
            raise RuntimeError("FeatureEngineer must be fitted before calling transform.")
        df = normalize_columns(df)
        features_df = self._derive_indicators(df)
        # Ensure identical column order
        features_df = features_df.reindex(columns=self.feature_names, fill_value=0.0)
        return self.scaler.transform(features_df.values)

    def fit_transform(self, df: pd.DataFrame) -> np.ndarray:
        """Fits and transforms in a single step."""
        return self.fit(df).transform(df)

    def _derive_indicators(self, df: pd.DataFrame) -> pd.DataFrame:
        """Calculates domain specific fraud features."""
        feats = pd.DataFrame(index=df.index)

        # Base amounts (with zero-division prevention)
        sanctioned = pd.to_numeric(df.get("sanctioned_amount", 0.0), errors="coerce").fillna(0.0)
        expenditure = pd.to_numeric(df.get("expenditure_amount", 0.0), errors="coerce").fillna(0.0)
        released = pd.to_numeric(df.get("released_amount", sanctioned), errors="coerce").fillna(sanctioned)
        recommended = pd.to_numeric(df.get("recommended_amount", sanctioned), errors="coerce").fillna(sanctioned)
        physical_pct = pd.to_numeric(df.get("physical_progress_pct", 0.0), errors="coerce").fillna(0.0)

        eps = 1.0  # INR 1 smoothing epsilon to prevent division by zero

        # Indicator 1: Cost Overrun Ratio (Expenditure vs Sanctioned)
        feats["cost_overrun_ratio"] = expenditure / (sanctioned + eps)

        # Indicator 2: Release Utilization Ratio (Expenditure vs Released)
        feats["release_utilization_ratio"] = expenditure / (released + eps)

        # Indicator 3: Sanction-to-Recommended Ratio
        feats["sanction_ratio"] = sanctioned / (recommended + eps)

        # Indicator 4: Financial Progress Percentage (Capped at 200% for extreme outlier detection)
        financial_pct = np.clip((expenditure / (sanctioned + eps)) * 100.0, 0.0, 200.0)
        feats["financial_progress_pct"] = financial_pct

        # Indicator 5: Physical Progress Percentage
        feats["physical_progress_pct"] = physical_pct

        # Indicator 6: Progress Gap (Crucial Ghost Work Flag: Money spent with little physical work)
        feats["progress_gap"] = financial_pct - physical_pct

        # Indicator 7: Cost Spent per Unit of Physical Progress
        unit_cost = expenditure / (physical_pct + 1.0)
        feats["cost_per_progress_unit"] = unit_cost

        # Indicator 8: Category Sanction Ratio (Budget scale vs sector baseline)
        if "category" in df.columns:
            cat_sanct_median = df["category"].map(self.category_sanction_medians).fillna(self.overall_median_sanctioned)
            cat_unit_median = df["category"].map(self.category_unit_cost_medians).fillna(self.overall_median_unit_cost)
        else:
            cat_sanct_median = self.overall_median_sanctioned
            cat_unit_median = self.overall_median_unit_cost

        feats["category_sanction_ratio"] = np.clip(sanctioned / (cat_sanct_median + eps), 0.2, 5.0)

        # Indicator 9: Category Unit Cost Ratio (Cost efficiency per % progress vs sector baseline)
        feats["category_unit_cost_ratio"] = np.clip(unit_cost / (cat_unit_median + eps), 0.2, 5.0)

        # Indicator 10: Temporal Completion Delay (Days past expected deadline)
        if "expected_completion_date" in df.columns and "actual_completion_date" in df.columns:
            exp_dt = pd.to_datetime(df["expected_completion_date"], errors="coerce")
            act_dt = pd.to_datetime(df["actual_completion_date"], errors="coerce")
            delays = (act_dt - exp_dt).dt.days.fillna(0.0)
            feats["completion_delay_days"] = np.clip(delays, -30.0, 365.0)
        elif "completion_delay_days" in df.columns:
            feats["completion_delay_days"] = np.clip(
                pd.to_numeric(df["completion_delay_days"], errors="coerce").fillna(0.0), -30.0, 365.0
            )
        else:
            feats["completion_delay_days"] = 0.0

        # Indicator 11: Geospatial Discrepancy (Distance in KM from claimed coordinates)
        if "gps_distance_km" in df.columns:
            feats["gps_distance_km"] = np.clip(
                pd.to_numeric(df["gps_distance_km"], errors="coerce").fillna(0.0), 0.0, 200.0
            )
        else:
            feats["gps_distance_km"] = 0.0

        # Indicator 12: Duplicate Photographic Evidence Flag (1.0 for duplicated image hash)
        if "duplicate_photo_flag" in df.columns:
            dup_s = df["duplicate_photo_flag"].astype(str).str.strip().str.lower()
            feats["duplicate_photo_flag"] = dup_s.isin(["yes", "true", "1"]).astype(float)
        else:
            feats["duplicate_photo_flag"] = 0.0

        # Fill any remaining NaNs or Infs
        feats = feats.replace([np.inf, -np.inf], np.nan).fillna(0.0)

        return feats


