# 4. Main Model: MPLADSFraudDetector (Isolation Forest)
# ---------------------------------------------------------------------------

class MPLADSFraudDetector:
    """
    Modular Anomaly Detection Engine for MPLADS projects using Isolation Forest.

    Provides:
    - fit(df)
    - predict(df)
    - predict_with_scores(df) -> Returns DataFrame with is_anomaly, risk_score (0-100), and fraud_reasons
    - save(filepath) / load(filepath)
    """

    def __init__(
        self,
        contamination: Union[str, float] = 0.08,
        n_estimators: int = 150,
        random_state: int = 42,
    ):
        """
        Parameters:
        - contamination: Expected proportion of outliers (e.g. 0.08 = ~8% anomalies).
        - n_estimators: Number of isolation trees.
        - random_state: Seed for reproducibility.
        """
        self.contamination = contamination
        self.n_estimators = n_estimators
        self.random_state = random_state

        self.model = IsolationForest(
            contamination=self.contamination,
            n_estimators=self.n_estimators,
            random_state=self.random_state,
            n_jobs=1,
        )
        self.engineer = MPLADSFeatureEngineer()
        self.is_fitted = False

        # Internal score thresholds for 0-100 calibration
        self.min_score_val = -0.5
        self.max_score_val = 0.5

    def fit(self, df: pd.DataFrame) -> "MPLADSFraudDetector":
        """Fits feature engineer and Isolation Forest on MPLADS dataset."""
        df_clean = normalize_columns(df)
        X = self.engineer.fit_transform(df_clean)
        self.model.fit(X)

        # Calibration parameters for normalizing risk scores to 0-100
        raw_decision_scores = self.model.decision_function(X)
        self.min_score_val = float(np.min(raw_decision_scores))
        self.max_score_val = float(np.max(raw_decision_scores))

        self.is_fitted = True
        return self

    def predict(self, df: pd.DataFrame) -> np.ndarray:
        """
        Returns binary predictions from Isolation Forest:
        1 for Normal, -1 for Anomaly
        """
        if not self.is_fitted:
            raise RuntimeError("Model must be fitted before running predictions.")
        df_clean = normalize_columns(df)
        X = self.engineer.transform(df_clean)
        return self.model.predict(X)

    def compute_risk_scores(self, decision_scores: np.ndarray) -> np.ndarray:
        """
        Converts Isolation Forest decision scores into a 0 to 100 Risk Score.
        Lower decision score indicates deeper isolation (higher anomaly).
        We invert and scale so:
        - 0-40: Normal / Low Risk
        - 41-65: Moderate Risk
        - 66-100: High Risk / Probable Fraud
        """
        span = (self.max_score_val - self.min_score_val) + 1e-8
        # Invert: decision_score near min_score_val becomes high risk
        normalized = (self.max_score_val - decision_scores) / span
        risk_scores = np.clip(normalized * 100.0, 0.0, 100.0)
        return np.round(risk_scores, 2)

    def predict_with_scores(self, df: pd.DataFrame, risk_threshold: float = 65.0) -> pd.DataFrame:
        """
        Runs the complete detection pipeline and enriches original records with:
        - is_anomaly: True/False
        - risk_score: 0.0 to 100.0
        - fraud_reasons: List of clear, understandable flags
        - risk_level: 'High', 'Medium', 'Low'
        """
        if not self.is_fitted:
            raise RuntimeError("Model must be fitted before running predictions.")

        df_clean = normalize_columns(df)
        X = self.engineer.transform(df_clean)

        raw_preds = self.model.predict(X)  # -1 = anomaly, 1 = normal
        decision_scores = self.model.decision_function(X)
        risk_scores = self.compute_risk_scores(decision_scores)

        results = df.copy().reset_index(drop=True)
        results["is_anomaly"] = (raw_preds == -1) | (risk_scores >= risk_threshold)
        results["risk_score"] = risk_scores

        # Categorize risk level
        results["risk_level"] = pd.cut(
            results["risk_score"],
            bins=[-np.inf, 40.0, 65.0, np.inf],
            labels=["Low", "Medium", "High"],
        )

        # Generate human-readable reasons for flagged records
        reasons_list = []
        df_clean_reset = df_clean.reset_index(drop=True)
        for idx, row in df_clean_reset.iterrows():
            curr_score = risk_scores[idx] if idx < len(risk_scores) else 0.0
            cat = str(row.get("category", ""))
            cat_sanct_median = self.engineer.category_sanction_medians.get(
                cat, self.engineer.overall_median_sanctioned
            )
            cat_unit_median = self.engineer.category_unit_cost_medians.get(
                cat, self.engineer.overall_median_unit_cost
            )

            if results.loc[idx, "is_anomaly"]:
                r = explain_fraud_reasons(
                    row,
                    curr_score,
                    category_sanction_median=cat_sanct_median,
                    category_unit_cost_median=cat_unit_median,
                )
                reasons_list.append("; ".join(r) if r else "Unusual combination of financial and progress parameters.")
            else:
                reasons_list.append("Within expected operational parameters.")

        results["fraud_reasons"] = reasons_list

        return results

    def save(self, filepath: str) -> None:
        """Persists trained detector and preprocessing state to disk."""
        if not self.is_fitted:
            raise RuntimeError("Cannot save an unfitted model.")
        parent_dir = os.path.dirname(os.path.abspath(filepath))
        if parent_dir:
            os.makedirs(parent_dir, exist_ok=True)
        joblib.dump(self, filepath)
        print(f"[+] Model successfully saved to: {filepath}")

    @staticmethod
    def load(filepath: str) -> "MPLADSFraudDetector":
        """Loads a persisted MPLADSFraudDetector instance."""
        if not os.path.exists(filepath):
            raise FileNotFoundError(f"Model file not found at: {filepath}")
        detector = joblib.load(filepath)
        print(f"[+] Model successfully loaded from: {filepath}")
        return detector


